"""Схема саммари.

Каждая секция формата — отдельное поле. Модель обязана заполнить их все, и
именно это не даёт ей растворить цифры, имена и оговорки в общей прозе.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

VideoType = Literal[
    "lecture",  # лекция, доклад, объяснение
    "interview",  # интервью, подкаст, диалог
    "tutorial",  # туториал, инструкция, разбор кода
    "news",  # новости, обзор событий
    "review",  # обзор продукта, сравнение
    "stream",  # длинный стрим, ама, созвон
    "other",
]


class Chapter(BaseModel):
    """Глава видео с таймкодом."""

    start: int = Field(description="Начало главы в секундах от начала видео.")
    title: str = Field(description="О чём эта часть. Коротко, по делу.")
    skippable: bool = Field(
        description="true, если часть можно пропустить: интро, вода, реклама, оффтоп."
    )


class Thesis(BaseModel):
    """Утверждение автора, а не тема разговора."""

    text: str = Field(
        description=(
            "Законченное утверждение с конкретикой. "
            "Не «автор говорит про рынок», а «автор ждёт падения рынка на ~20% к Q3»."
        )
    )
    basis: str | None = Field(
        default=None,
        description=(
            "Чем автор обосновывает тезис: данные, опыт, ссылка на исследование. "
            "null, если обоснования в видео не было."
        ),
    )
    start: int | None = Field(
        default=None, description="Секунда, где тезис звучит. null, если размазан по видео."
    )
    speaker: str | None = Field(
        default=None,
        description="Кто это утверждает. Заполнять для интервью и диалогов, иначе null.",
    )


class Facts(BaseModel):
    """Фактура — то, что теряется в саммари первым.

    Это сводка того, за чем сюда возвращаются: цифры, имена, названия. Списки
    должны быть полными по смыслу, но не всеядными — до 10 пунктов в каждом,
    самое важное первым.
    """

    numbers: list[str] = Field(
        description=(
            "Числа, на которых держится содержание: результаты, цены, сроки, "
            "дозировки, размеры выборки. С единицами и коротким контекстом: "
            "«+30% recall», «$0.13 за 1000 запросов», «вес 188 → 186 фунтов».\n"
            "Не всякое произнесённое число: «стейк отдыхал 10 минут» или "
            "«5 млн подписчиков» — шум, если ни один тезис на них не опирается. "
            "Максимум 10 пунктов, самое значимое первым."
        )
    )
    names: list[str] = Field(
        description="Люди, компании, организации — с пояснением, кто это, если неочевидно."
    )
    tools: list[str] = Field(
        description="Названные инструменты, продукты, библиотеки, книги, статьи, фильмы."
    )
    links: list[str] = Field(
        description="Ссылки и адреса, произнесённые вслух или показанные на экране."
    )
    terms: list[str] = Field(
        description="Термины, которые автор вводит и определяет, — с его определением."
    )


class Summary(BaseModel):
    video_type: VideoType = Field(description="Тип видео — от него зависит, что важнее.")

    verdict: str = Field(
        description=(
            "Максимум три предложения: что это за видео и кому оно нужно. "
            "Не пересказывай здесь содержание и не выноси сюда главный тезис — "
            "для этого есть theses. Дублирование съедает экран телефона и "
            "заставляет читать одно и то же дважды."
        )
    )
    watch_advice: str = Field(
        description=(
            "Одна строка: смотреть целиком, смотреть с такой-то минуты, "
            "или достаточно этого саммари. С обоснованием."
        )
    )

    theses: list[Thesis] = Field(
        description="5-9 ключевых утверждений, в порядке важности, а не в порядке видео."
    )
    chapters: list[Chapter] = Field(
        description=(
            "Карта видео по таймкодам. Столько глав, сколько реально смысловых частей: "
            "для 10-минутного ролика 3-4, для трёхчасового стрима 15-25."
        )
    )

    facts: Facts

    practical: list[str] = Field(
        description=(
            "Шаги, инструкции, рецепт, чеклист — если в видео есть, что применить. "
            "Пустой список, если видео не про действия."
        )
    )
    caveats: list[str] = Field(
        description=(
            "Оговорки и условия применимости: «не работает на Windows», «только для "
            "юрлиц», «автор не проверял», «бенчмарк внутренний». Плюс спорные "
            "утверждения без пруфов. Теряется чаще всего и стоит дороже всего."
        )
    )
    disagreements: list[str] = Field(
        description=(
            "Точки, где собеседники не сошлись, с позицией каждого. "
            "Для интервью и дискуссий это и есть суть. Иначе пустой список."
        )
    )
    sponsored: list[str] = Field(
        description=(
            "Рекламные интеграции и места, где автор продаёт своё, "
            "с таймкодом в формате «12:30 — интеграция спонсора X». Иначе пустой список."
        )
    )
    unclear: list[str] = Field(
        description=(
            "Места, где распознавание речи сбоило и смысл восстановить не удалось, "
            "с таймкодом. Не додумывать — честно перечислить. Иначе пустой список."
        )
    )
